from pathlib import Path
from typing import Callable

REPO = Path(__file__).resolve().parents[1]
SERVER_DIR = REPO / "concepts" / "10-langfuse" / "server"
ENV_FILE = SERVER_DIR / ".env"
BASE_URL = "http://localhost:3000"
PLUGIN_ID = "langfuse-observability@claude-plugins-official"
IMAGE_TAG = "4.80.0"
HOOK_LOG = "~/.claude/state/langfuse_hook.log"
# Host ports the stack publishes (web, worker, AI gateway, postgres, redis, clickhouse ×2, minio ×2).
PORTS = (3000, 3030, 3031, 5432, 6379, 8123, 9000, 9090, 9091)


# ----------------------------------------------------------------------------- .env for docker compose

def generate_env(token: Callable[[int], str] = secrets.token_hex) -> dict[str, str]:
    """Fresh secrets plus headless-init values. Shared secrets are generated once and reused where the upstream
    compose file expects them to match (DATABASE_URL ↔ POSTGRES_PASSWORD, S3 keys ↔ MINIO_ROOT_PASSWORD)."""
    postgres, minio = token(16), token(16)
    return {
        "LANGFUSE_IMAGE_TAG": IMAGE_TAG,
        "TELEMETRY_ENABLED": "false",
        "NEXTAUTH_URL": BASE_URL,
        "NEXTAUTH_SECRET": token(32),
        "SALT": token(32),
        "ENCRYPTION_KEY": token(32),
        "POSTGRES_PASSWORD": postgres,
        "DATABASE_URL": f"postgresql://postgres:{postgres}@postgres:5432/postgres",
        "CLICKHOUSE_PASSWORD": token(16),
        "REDIS_AUTH": token(16),
        "MINIO_ROOT_PASSWORD": minio,
        "LANGFUSE_S3_EVENT_UPLOAD_SECRET_ACCESS_KEY": minio,
        "LANGFUSE_S3_MEDIA_UPLOAD_SECRET_ACCESS_KEY": minio,
        "LANGFUSE_S3_BATCH_EXPORT_SECRET_ACCESS_KEY": minio,
        "LANGFUSE_INIT_ORG_ID": "lab-org",
        "LANGFUSE_INIT_ORG_NAME": "Claude Code Lab",
        "LANGFUSE_INIT_PROJECT_ID": "claude-code-lab",
        "LANGFUSE_INIT_PROJECT_NAME": "claude-code-lab",
        "LANGFUSE_INIT_PROJECT_PUBLIC_KEY": f"pk-lf-{token(16)}",
        "LANGFUSE_INIT_PROJECT_SECRET_KEY": f"sk-lf-{token(24)}",
        "LANGFUSE_INIT_USER_EMAIL": "lab@example.com",
        "LANGFUSE_INIT_USER_NAME": "Lab",
        "LANGFUSE_INIT_USER_PASSWORD": token(12),
    }


def write_env(path: Path, values: dict[str, str]) -> None:
    """Write KEY=VALUE lines readable only by the owner (the file holds secrets)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write("# Generated by ./lab langfuse up. Secret: never commit. Keep it once Langfuse has booted.\n")
        fh.writelines(f"{key}={value}\n" for key, value in values.items())
    os.chmod(path, 0o600)  # also tighten a file that already existed


def read_env(path: Path) -> dict[str, str]:
    values = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip()
    return values


def ensure_env(path: Path = ENV_FILE) -> tuple[dict[str, str], bool]:
    """Return (values, created). Never overwrite: Langfuse applies LANGFUSE_INIT_* only on its first boot, so
    new keys after that would be rejected (401) forever."""
    if path.exists():
        return read_env(path), False
    values = generate_env()
    write_env(path, values)
    return values, True


# ----------------------------------------------------------------------------- plugin wiring

def trace_tags(lab: str, kind: str, **extra: object) -> str:
    """Comma list for CC_LANGFUSE_TRACE_TAGS, e.g. 'lab:01-single-agent,kind:architecture,ticket:T01'."""
    tags = [f"lab:{lab}", f"kind:{kind}"]
    tags += [f"{key}:{value}" for key, value in extra.items() if value is not None]
    return ",".join(tags)


def plugin_env(env: dict[str, str], tags: str) -> dict[str, str]:
    """Env vars the plugin reads. Plain env vars win over the plugin's stored (machine-wide) userConfig."""
    return {
        "LANGFUSE_PUBLIC_KEY": env["LANGFUSE_INIT_PROJECT_PUBLIC_KEY"],
        "LANGFUSE_SECRET_KEY": env["LANGFUSE_INIT_PROJECT_SECRET_KEY"],
        "LANGFUSE_BASE_URL": BASE_URL,
        "LANGFUSE_USER_ID": "lab",
        "CC_LANGFUSE_TRACE_TAGS": tags,
    }


def score_payloads(session_id: str, accepted: bool, regressions: int, summary: str) -> list[dict]:
    """Bodies for POST /api/public/scores, attached to the Claude session (one Langfuse session per run)."""
    return [
        {"name": "accepted", "value": 1 if accepted else 0, "dataType": "BOOLEAN",
         "sessionId": session_id, "comment": summary},
        {"name": "regressions", "value": regressions, "dataType": "NUMERIC", "sessionId": session_id},
    ]


def session_url(env: dict[str, str], session_id: str) -> str:
    return f"{BASE_URL}/project/{env['LANGFUSE_INIT_PROJECT_ID']}/sessions/{session_id}"


# ----------------------------------------------------------------------------- services (Docker, HTTP)

def docker_ok(docker: str = "docker") -> bool:
    """True when the Docker engine answers (Docker Desktop running, WSL integration on)."""
    try:
        return subprocess.run([docker, "info"], capture_output=True, timeout=15).returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def port_conflicts(ports: tuple[int, ...] = PORTS, host: str = "127.0.0.1") -> list[int]:
    """Ports something else already listens on. Best effort: on WSL2, a port taken on the Windows side may not show."""
    busy = []
    for port in ports:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
            try:
                probe.bind((host, port))
            except OSError:
                busy.append(port)
    return busy


def compose(*args: str, capture: bool = False) -> subprocess.CompletedProcess:
    """docker compose with the pinned upstream file plus the localhost-only override, run in SERVER_DIR."""
    cmd = ["docker", "compose", "-f", "docker-compose.yml", "-f", "docker-compose.lab.yml", *args]
    return subprocess.run(cmd, cwd=SERVER_DIR, text=True, capture_output=capture)


def healthy(base_url: str = BASE_URL, timeout: float = 3.0) -> bool:
    try:
        with urllib.request.urlopen(f"{base_url}/api/public/health", timeout=timeout) as resp:
            return resp.status == 200
    except Exception:  # noqa: BLE001 - any failure means "not healthy"
        return False


def runtime_ok() -> bool:
    """The plugin's hook runs with `uv` (preferred) or with `python3` plus the langfuse SDK."""
    if shutil.which("uv"):
        return True
    try:
        return subprocess.run(["python3", "-c", "import langfuse"], capture_output=True, timeout=30).returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def plugin_installed() -> bool:
    """True when Claude Code knows the plugin in any scope (it may still be disabled where you are)."""
    try:
        proc = subprocess.run(["claude", "plugin", "list", "--json"], capture_output=True, text=True, timeout=60,
                              stdin=subprocess.DEVNULL)
    except (OSError, subprocess.TimeoutExpired):
        return False
    return PLUGIN_ID in proc.stdout


def api(env: dict[str, str], method: str, path: str, body: dict | None = None, base_url: str = BASE_URL) -> dict:
    """Call Langfuse's public API with the project's keys (basic auth: public key as user, secret as password)."""
    token = base64.b64encode(
        f"{env['LANGFUSE_INIT_PROJECT_PUBLIC_KEY']}:{env['LANGFUSE_INIT_PROJECT_SECRET_KEY']}".encode()).decode()
    request = urllib.request.Request(
        f"{base_url}{path}", method=method, data=json.dumps(body).encode() if body is not None else None,
        headers={"Authorization": f"Basic {token}", "Content-Type": "application/json"},
    )
    with urllib.request.urlopen(request, timeout=30) as resp:
        raw = resp.read()
    return json.loads(raw) if raw else {}


def post_scores(env: dict[str, str], payloads: list[dict], api: Callable = api) -> list[str]:
    """Post each score; return the errors instead of raising (scoring must never lose a run's result)."""
    errors = []
    for payload in payloads:
        try:
            api(env, "POST", "/api/public/scores", payload)
        except Exception as exc:  # noqa: BLE001
            errors.append(f"{payload.get('name')}: {exc}")
    return errors
