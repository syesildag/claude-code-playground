"""Helpers for the self-hosted Langfuse used by `./lab langfuse` and `--trace` (stdlib only).

The lab runs Langfuse from concepts/10-langfuse/server and points Langfuse's official Claude Code plugin
(`langfuse-observability`) at it through environment variables, one sandbox at a time.
"""

